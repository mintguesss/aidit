const core = (s: string) => s.normalize("NFKC").toUpperCase().replace(/\s|學分學程|微學程|學程|服務|趨勢/g, "");

/** 「AI微學程」「人工智慧應用」對到課程系統裡的學程單位；對不到或對到好幾個就不猜 */
export function findProgramUnit(school: string, name: string): { code: string; name: string } | undefined {
  const want = core(name);
  if (want.length < 2) return undefined;
  const all = PROGRAM_UNITS[school] ?? [];
  const exact = all.filter(([, n]) => core(n) === want);
  const hits = exact.length > 0 ? exact : all.filter(([, n]) => core(n).includes(want) || want.includes(core(n)));
  return hits.length === 1 ? { code: hits[0]![0], name: hits[0]![1] } : undefined;
}
